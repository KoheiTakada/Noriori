"""Generate Android foundations from the product's single token source."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
tokens = json.loads((ROOT / "design/tokens.json").read_text())
java = ["// Generated by tools/sync_design_tokens.py. Edit design/tokens.json.",
        "package jp.kohei.norisugoshi;", "", "final class DesignTokens {"]
for category, values in tokens.items():
    java.append(f"    static final class {category.title()} {{")
    for name, value in values.items():
        literal = "0xFF" + value[1:] if category == "color" else str(value)
        java.append(f"        static final int {name.upper()} = {literal};")
    java.append("    }")
java.append("    private DesignTokens() { }\n}")
(ROOT / "app/src/main/java/jp/kohei/norisugoshi/DesignTokens.java").write_text("\n".join(java) + "\n")
colors = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated. Edit design/tokens.json. -->', '<resources>']
for name, value in tokens['color'].items():
    # View components consume Java tokens; XML contains theme/notification references.
    if name not in {'canvas', 'surface', 'ink', 'muted', 'primary', 'danger'}:
        continue
    colors.append(f'    <color name="ds_{name}">{value}</color>')
for alias, name in {'brand_primary': 'primary',
                    'surface': 'canvas', 'text_primary': 'ink', 'status_warning': 'danger'}.items():
    colors.append(f'    <color name="{alias}">@color/ds_{name}</color>')
colors.append('</resources>')
(ROOT / 'app/src/main/res/values/colors.xml').write_text('\n'.join(colors) + '\n')
print('Generated DesignTokens.java and colors.xml')
